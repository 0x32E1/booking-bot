class Tr:
    """Translator bound to one language."""

    __slots__ = ("lang",)

    def __init__(self, lang: str | None) -> None:
        self.lang = lang if lang in LANGS else "uz"

    def __call__(self, key: str, **kw) -> str:
        entry = TEXTS.get(key)
        if entry is None:
            return key
        text = entry.get(self.lang) or entry["uz"]
        if kw:
            kw = {k: (v(self) if callable(v) else v) for k, v in kw.items()}
            text = text.format(**kw)
        return text


def variants(key: str) -> set[str]:
    """All language versions of a button label (to match reply-keyboard presses)."""
    return set(TEXTS[key].values())
